# GUI の Web タブから渡された cookie を Netscape 形式で保存する。
# Headless の別ブラウザは使わない。

from __future__ import annotations

import logging
from pathlib import Path
from typing import Any

logger = logging.getLogger("MOMOKA.music.plugins.youtube_cookie")

# MOMOKA/music/plugins/youtube_cookie_fetcher.py → parents[3]
_REPO_ROOT = Path(__file__).resolve().parents[3]

# yt-dlp がログイン済みと扱う cookie 名。これが無い結果では原本を上書きしない。
_AUTH_COOKIE_NAMES = frozenset(
    {
        "LOGIN_INFO",
        "SAPISID",
        "SID",
        "__Secure-1PSID",
        "__Secure-3PSID",
        "__Secure-1PAPISID",
        "__Secure-3PAPISID",
    }
)
# 保存対象のドメイン末尾
_COOKIE_DOMAIN_SUFFIXES = ("youtube.com", "google.com")


# ニコニコのログイン済み cookie。これが無い結果では nico_cookies.txt を上書きしない。
_NICO_AUTH_COOKIE_NAMES = frozenset({"user_session"})
# ニコニコの保存対象ドメイン
_NICO_COOKIE_DOMAIN_SUFFIXES = ("nicovideo.jp", "nico.ms")


def _domain_allowed(domain: str, suffixes: tuple[str, ...] = _COOKIE_DOMAIN_SUFFIXES) -> bool:
    """指定ドメインの cookie か。部分一致の偽ドメインは除外する。"""
    # 先頭ドットを外したホスト
    host = domain.lstrip(".").lower()
    # 完全一致か、サブドメインか
    return any(host == suffix or host.endswith("." + suffix) for suffix in suffixes)


def netscape_cookie_file(
    cookies: list[dict],
    *,
    suffixes: tuple[str, ...] = _COOKIE_DOMAIN_SUFFIXES,
) -> str:
    """ブラウザ cookie 配列を yt-dlp 向け Netscape 形式にする。"""
    # 同じ鍵は最後の値を採用する
    rows: dict[tuple[str, str, str], str] = {}
    # 各 cookie を 1 行に整形する
    for cookie in cookies:
        # 辞書以外は捨てる
        if not isinstance(cookie, dict):
            continue
        # 名前と値
        name = str(cookie.get("name") or "")
        value = str(cookie.get("value") or "")
        # タブや改行を含む値は Netscape 形式を壊すので除外する
        if not name or any(ch in name or ch in value for ch in "\t\r\n"):
            continue
        # ドメイン
        domain = str(cookie.get("domain") or "")
        # 対象外ドメイン
        if not _domain_allowed(domain, suffixes):
            continue
        # 先頭ドットはサブドメインを含む印
        include_sub = "TRUE" if domain.startswith(".") else "FALSE"
        # パス
        path = str(cookie.get("path") or "/")
        # Secure
        secure = "TRUE" if cookie.get("secure") else "FALSE"
        # Electron は expirationDate、Playwright は expires
        expires = cookie.get("expires", cookie.get("expirationDate"))
        # セッション cookie は 0
        if not isinstance(expires, (int, float)) or expires < 0:
            expires_int = 0
        else:
            expires_int = int(expires)
        # 並び用の鍵
        key = (domain, path, name)
        # 行本体
        rows[key] = (
            f"{domain}\t{include_sub}\t{path}\t{secure}\t{expires_int}\t{name}\t{value}"
        )
    # yt-dlp が Netscape 形式と認識するヘッダ
    lines = [
        "# Netscape HTTP Cookie File",
        "# https://curl.se/docs/http-cookies.html",
        "# Generated by MOMOKA GUI web tab. Do not edit.",
        "",
    ]
    # 安定ソート
    lines.extend(rows[key] for key in sorted(rows))
    # 末尾改行
    return "\n".join(lines) + "\n"


def _cookie_names(cookies: list[dict]) -> set[str]:
    """cookie 名の集合。"""
    return {str(item.get("name") or "") for item in cookies if isinstance(item, dict) and item.get("name")}


def _has_auth_cookie(cookies: list[dict], auth_names: frozenset[str] = _AUTH_COOKIE_NAMES) -> bool:
    """ログイン済みとみなせる cookie があるか。"""
    return bool(_cookie_names(cookies) & auth_names)


def _changed_cookie_names(previous: str, current: str) -> list[str]:
    """Netscape 本文を比べ、値の変わった cookie 名を返す。"""

    def parse(text: str) -> dict[str, str]:
        # 名前→値
        found: dict[str, str] = {}
        # 行ごと
        for line in text.splitlines():
            # コメントと空行は無視
            if not line or line.startswith("#"):
                continue
            # Netscape は 7 列
            parts = line.split("\t")
            if len(parts) < 7:
                continue
            found[parts[5]] = parts[6]
        return found

    # 前後
    old = parse(previous)
    new = parse(current)
    # 追加・更新・削除
    return sorted(name for name in set(old) | set(new) if old.get(name) != new.get(name))


def _cookie_destination() -> Path:
    """music.youtube_cookie_file をリポジトリルート基準で返す。"""
    # 遅延インポート（設定ローダの循環を避ける）
    from MOMOKA.config.loader import load_merged_config

    # 統合設定
    music = (load_merged_config().get("music") or {})
    # 未指定はプロジェクト直下
    raw = Path(str(music.get("youtube_cookie_file") or "youtube_cookies.txt"))
    # 相対パスはリポジトリルート
    return raw if raw.is_absolute() else (_REPO_ROOT / raw)


def youtube_account_for_gui() -> dict[str, Any]:
    """Web タブの自動入力に使うアカウント。ログへは出さない。"""
    # 遅延インポート
    from MOMOKA.config.loader import load_merged_config

    # music 節
    music = load_merged_config().get("music") or {}
    # music.youtube_account
    account = music.get("youtube_account") or {}
    # 辞書でなければ空
    if not isinstance(account, dict):
        account = {}
    # music.niconico（自動入力専用。値はログに出さない）
    niconico = music.get("niconico") or {}
    if not isinstance(niconico, dict):
        niconico = {}
    # 読み直し間隔
    try:
        reload_minutes = int(account.get("reload_minutes", 60))
    except (TypeError, ValueError):
        reload_minutes = 60
    # 下限 15 分、上限 24 時間
    reload_minutes = max(15, min(24 * 60, reload_minutes))
    return {
        "email": str(account.get("email") or ""),
        "password": str(account.get("password") or ""),
        "reload_minutes": reload_minutes,
        "niconico_email": str(niconico.get("email") or ""),
        "niconico_password": str(niconico.get("password") or ""),
    }


def _auth_row_present(body: str, auth_names: frozenset[str]) -> bool:
    """Netscape 本文に認証 cookie の行があるか。"""
    for line in body.splitlines():
        # コメントと空行は無視。#HttpOnly_ 付きも認証行として見る。
        raw = line[len("#HttpOnly_") :] if line.startswith("#HttpOnly_") else line
        if not raw or raw.startswith("#") or raw.count("\t") < 6:
            continue
        if raw.split("\t")[5] in auth_names:
            return True
    return False


def _save_site_cookies(
    cookies: list,
    *,
    suffixes: tuple[str, ...],
    auth_names: frozenset[str],
    dest: Path,
    label: str,
) -> dict[str, Any]:
    """サイトの cookie を Netscape 原本へ書く。未ログインや無変化では原本を壊さない。"""
    # リスト以外は拒否
    if not isinstance(cookies, list):
        return {"ok": False, "error": "invalid_cookies", "changed": []}
    # 認証 cookie が無ければ何も書かない
    if not _has_auth_cookie(cookies, auth_names):
        return {"ok": False, "error": "not_logged_in", "changed": []}
    # Netscape 本文
    body = netscape_cookie_file(cookies, suffixes=suffixes)
    # フィルタ後も認証行があるか
    if not _auth_row_present(body, auth_names):
        return {"ok": False, "error": "not_logged_in", "changed": []}
    # 既存
    previous = ""
    if dest.is_file():
        try:
            previous = dest.read_text(encoding="utf-8")
        except OSError as exc:
            logger.warning("Could not read existing %s cookies: %s", label, exc)
    # 変化した名前。値はログに出さない。
    changed = _changed_cookie_names(previous, body)
    # 同じ内容なら書き戻さない
    if previous and not changed:
        return {"ok": True, "error": None, "changed": [], "size": len(body.encode("utf-8"))}
    # 親ディレクトリ
    dest.parent.mkdir(parents=True, exist_ok=True)
    # 途中失敗で原本を空にしない
    tmp = dest.with_suffix(dest.suffix + ".tmp")
    tmp.write_text(body, encoding="utf-8", newline="\n")
    tmp.replace(dest)
    logger.info(
        "%s cookies updated from GUI web tab (%s): %s",
        label,
        len(changed) if previous else "initial",
        ", ".join(changed[:12]) if changed else "initial write",
    )
    return {
        "ok": True,
        "error": None,
        "changed": changed,
        "size": dest.stat().st_size,
    }


def save_browser_cookies(cookies: list) -> dict[str, Any]:
    """GUI ブラウザの YouTube cookie を原本へ書く。"""
    # 書き出し
    saved = _save_site_cookies(
        cookies,
        suffixes=_COOKIE_DOMAIN_SUFFIXES,
        auth_names=_AUTH_COOKIE_NAMES,
        dest=_cookie_destination(),
        label="YouTube",
    )
    # 未保存なら runtime も触らない
    if not saved.get("ok") or not saved.get("changed"):
        return saved
    # runtime へ載せる
    try:
        from MOMOKA.music.plugins.ytdlp_wrapper import ensure_youtube_cookies_loaded

        ensure_youtube_cookies_loaded(reason="gui-web")
    except Exception:
        logger.exception("Failed to reload YouTube cookies after GUI export")
        return {
            "ok": False,
            "error": "reload_failed",
            "changed": saved.get("changed") or [],
            "size": saved.get("size"),
        }
    return saved


def save_niconico_cookies(cookies: list) -> dict[str, Any]:
    """GUI ブラウザのニコニコ cookie を nico_cookies.txt へ書く。次の再生が読む。"""
    # 再生側と同じ絶対パス
    from MOMOKA.music.plugins.ytdlp_wrapper import NICO_COOKIE_PATH

    return _save_site_cookies(
        cookies,
        suffixes=_NICO_COOKIE_DOMAIN_SUFFIXES,
        auth_names=_NICO_AUTH_COOKIE_NAMES,
        dest=NICO_COOKIE_PATH,
        label="Niconico",
    )
